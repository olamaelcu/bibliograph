-- Retire the follow-graph mirror.
--
-- `follows` was written only by `net.olamaelcu.livtet.biblio.graph.follow`, and
-- that procedure is gone: the social feeds read
-- `net.olamaelcu.livtet.biblio.follow` records straight from the reader's repo
-- (`feedAuthorDids` in `xrpc-router.ts`), so nothing ever read this table.
--
-- The table was itself only reachable for one release: its first DDL,
-- `0011_follows.sql`, never entered `meta/_journal.json` and so never ran, which
-- is why production had no `follows` table and every `graph.follow` call failed
-- with 42P01 in silence. `0021_follows` created it and `0022_drop_follows` (this
-- file) removes it again. Both are idempotent, so an environment that never got
-- as far as either ends up correct.
DROP TABLE IF EXISTS follows;
